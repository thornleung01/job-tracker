"""Generate the data the TypeScript pipeline needs from the Python source of truth.

    python scripts/build_rules_json.py            # rewrites the two generated files
    python scripts/build_rules_json.py --check    # exit 1 if either is out of date, writes nothing

Writes web/src/pipeline/rules.json (jobtracker/rules.yaml, verbatim) and web/src/pipeline/unicodeTables.ts
(the few places where Python's str methods differ from JavaScript's: casefold, titlecase, combining classes).
Commit both outputs. The vitest suite fails when rules.json drifts from rules.yaml, and so does --check.
unicodeTables.ts depends on the Unicode version of the Python that runs this (named in its second line).
"""
from __future__ import annotations

import argparse
import json
import sys
import unicodedata
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
RULES_YAML = ROOT / "jobtracker" / "rules.yaml"
OUT_DIR = ROOT / "web" / "src" / "pipeline"


def build_rules() -> str:
    raw = yaml.safe_load(RULES_YAML.read_text(encoding="utf-8"))
    return json.dumps(raw, indent=2, ensure_ascii=False) + "\n"


def _ranges(points: list[int]) -> list[list[int]]:
    out: list[list[int]] = []
    for p in points:
        if out and out[-1][1] + 1 == p:
            out[-1][1] = p
        else:
            out.append([p, p])
    return out


def build_unicode_tables() -> str:
    combining, fold, title = [], {}, {}
    for cp in range(0x110000):
        if 0xD800 <= cp < 0xE000:
            continue
        ch = chr(cp)
        if unicodedata.combining(ch):
            combining.append(cp)
        # Per-character: JS's toLowerCase is the base, these are the exceptions where Python's casefold differs.
        if ch.casefold() != ch.lower():
            fold[ch] = ch.casefold()
        if ch.title() != ch.upper():
            title[ch] = ch.title()

    def lit(s: str) -> str:
        return "".join(f"\\u{{{ord(c):x}}}" for c in s)

    lines = [
        "// Generated by scripts/build_rules_json.py. Do not edit.",
        f"// Python unicodedata {unicodedata.unidata_version}",
        "",
        "/** Inclusive code point ranges whose canonical combining class is not 0 (unicodedata.combining). */",
        "export const COMBINING_RANGES: ReadonlyArray<readonly [number, number]> = [",
    ]
    lines += [f"  [0x{a:x}, 0x{b:x}]," for a, b in _ranges(combining)]
    lines += ["];", "", "/** Characters whose str.casefold() differs from JS toLowerCase(). */",
              "export const CASEFOLD_EXCEPTIONS: Readonly<Record<string, string>> = {"]
    lines += [f'  "{lit(k)}": "{lit(v)}",' for k, v in fold.items()]
    lines += ["};", "", "/** Characters whose str.title() differs from JS toUpperCase() (used by capitalize). */",
              "export const TITLECASE_EXCEPTIONS: Readonly<Record<string, string>> = {"]
    lines += [f'  "{lit(k)}": "{lit(v)}",' for k, v in title.items()]
    lines += ["};", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Generate web/src/pipeline/rules.json and unicodeTables.ts from the Python source of truth.")
    ap.add_argument("--check", action="store_true", help="exit 1 if the generated files are out of date, and write nothing")
    args = ap.parse_args(argv)
    outputs = {OUT_DIR / "rules.json": build_rules(), OUT_DIR / "unicodeTables.ts": build_unicode_tables()}
    if args.check:
        stale = [path.name for path, text in outputs.items() if not path.exists() or path.read_text(encoding="utf-8") != text]
        print(f"out of date, run scripts/build_rules_json.py: {', '.join(stale)}" if stale else "generated files up to date")
        return 1 if stale else 0
    for path, text in outputs.items():
        path.write_text(text, encoding="utf-8")
    print(f"wrote {' and '.join(str(p) for p in outputs)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
